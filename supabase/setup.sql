-- ROUTINE_VIBE / Study With Gazelle
-- Run ONLY in the NEW Supabase project's SQL Editor.
-- This creates the app's initial private profiles and To-Do tables.

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Study partner',
  created_at timestamptz not null default now()
);

create table if not exists public.todos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'New task',
  is_done boolean not null default false,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  subtitle text,
  note text
);

create index if not exists todos_user_position_idx on public.todos(user_id, position, created_at);
alter table public.profiles enable row level security;
alter table public.todos enable row level security;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles for select to authenticated using (auth.uid() = user_id);
drop policy if exists profiles_insert_own on public.profiles;
create policy profiles_insert_own on public.profiles for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists todos_select_own on public.todos;
create policy todos_select_own on public.todos for select to authenticated using (auth.uid() = user_id);
drop policy if exists todos_insert_own on public.todos;
create policy todos_insert_own on public.todos for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists todos_update_own on public.todos;
create policy todos_update_own on public.todos for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists todos_delete_own on public.todos;
create policy todos_delete_own on public.todos for delete to authenticated using (auth.uid() = user_id);

alter table public.profiles add column if not exists username text;
create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username)) where username is not null;

create or replace function public.handle_new_study_gazelle_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (user_id, display_name, username)
  values (new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', new.raw_user_meta_data ->> 'username', 'Study partner'),
    nullif(lower(new.raw_user_meta_data ->> 'username'), ''))
  on conflict (user_id) do update set
    display_name = excluded.display_name,
    username = coalesce(excluded.username, public.profiles.username);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_study_gazelle on auth.users;
create trigger on_auth_user_created_study_gazelle after insert on auth.users
for each row execute procedure public.handle_new_study_gazelle_user();

create or replace function public.get_total_members()
returns bigint language sql stable security definer set search_path = public, auth as $$
  select count(*)::bigint from auth.users where coalesce(is_anonymous, false) = false;
$$;
revoke all on function public.get_total_members() from public;
grant execute on function public.get_total_members() to authenticated;
